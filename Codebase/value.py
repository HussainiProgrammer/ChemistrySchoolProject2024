def toInt(number):
    if number == int(number): number = int(number)
    return number

class Value:
    def __init__(self, quantity: str, value: int|float|ScientificNotation, unit: str="", objects:list[str]=[]):
        self.value = value
        self.quantity = quantity
        self.unit = unit
        self.objects = objects

        for index, object in enumerate(self.objects):
            if type(object) == str:
                if (formula := findSubstance(object)): self.objects[index] = Substance(formula[0])
                elif object.isdigit(): self.objects[index] = int(object)

    def change_unit(self, newUnit: str):
        if self.unit != newUnit:
            self.value = toInt(round(unit_conversion[f'{self.unit}-{newUnit}'](self.value), 9))
            self.unit = newUnit

    def in_another_unit(self, newUnit: str):
        if self.unit != newUnit:
            return Value(self.quantity, toInt(round(unit_conversion[f'{self.unit}-{newUnit}'](self.value), 2)), unit=newUnit, objects=self.objects)
        
    def LaTeX(self):
        return f"{self.value.LaTeX() if type(self.value) == ScientificNotation else str(self.value)}{re.sub("(.+)/(.+)", "\\\\frac{\\1}{\\2}", self.unit)}"
